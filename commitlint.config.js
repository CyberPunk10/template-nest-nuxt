// Проверка сообщения коммита. Запускается сама при `git commit` через хук
// .husky/commit-msg; хук ставится при `pnpm install` (скрипт prepare).
//
// ─── Формат ─────────────────────────────────────────────────────────────────
//
//   тип(область): описание
//
//   - тип — обязателен, из списка ниже;
//   - (область) — необязательна: часть проекта, например (frontend),
//     (backend), (auth), (docs);
//   - описание — со строчной буквы, без точки в конце, по-английски,
//     в повелительном наклонении: «add», «fix», а не «added», «fixes»;
//   - вся первая строка — не длиннее 100 символов;
//   - после первой строки — пустая строка и, если нужно, подробности.
//
// ─── Типы и что они значат для релиза ───────────────────────────────────────
//
//   От типа зависит, попадёт ли изменение в CHANGELOG и какой будет
//   следующая версия шаблона (релиз — теги <вариант>@<версия>).
//
//   feat      новая возможность        следующий минор 0.1.0 → 0.2.0, в CHANGELOG
//   fix       исправление ошибки       следующий патч  0.1.0 → 0.1.1, в CHANGELOG
//   perf      ускорение                следующий патч, в CHANGELOG
//   revert    откат коммита            следующий патч, в CHANGELOG
//   docs      документация             на версию не влияет
//   refactor  переделка без изменения поведения
//   test      тесты
//   build     сборка, зависимости
//   ci        CI и workflow
//   chore     прочее обслуживание
//   style     форматирование кода
//
//   Ломающее изменение — `!` после типа: `feat(auth)!: rename session cookie`.
//   Пока версия 0.x, оно поднимает минор (0.1.0 → 0.2.0), после 1.0 — мажор.
//
//   Как выбрать: заметит ли изменение тот, кто создал проект из шаблона?
//   Заметит и это новое — feat; раньше было сломано — fix; не заметит —
//   refactor / docs / test / build / ci / chore.
//
//   Коммиты слияния («Merge branch 'main' into auth-session») не проверяются.
//
// ─── Примеры ────────────────────────────────────────────────────────────────
//
//   ✓ feat(auth): add password reset
//   ✓ fix(frontend): keep sidebar state after reload
//   ✓ docs: describe deployment to a VPS
//   ✗ Added password reset          — нет типа
//   ✗ rework: tidy sidebar          — неизвестный тип (нужен refactor)
//   ✗ feat: Add password reset      — описание с заглавной буквы
//   ✗ fix: keep sidebar state.      — точка в конце
//
// ─── Если проверка мешает ───────────────────────────────────────────────────
//
//   git commit --no-verify -m "..."     пропустить проверку один раз (или -n)
//
//   Коммит с неправильным типом не попадёт в CHANGELOG и не поднимет версию.
//   Обходить стоит только осознанно, например для временного коммита, который
//   потом будет переписан.
export default {
  extends: ['@commitlint/config-conventional'],
}
